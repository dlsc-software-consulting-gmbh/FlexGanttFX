package com.flexganttfx.view.util;

/**
 * An enumerator used for specifying the position of a control or an activity.
 *
 * @since 1.0
 */
public enum Position {

	/**
	 * The first element.
	 */
	FIRST,

	/**
	 * An element somewhere in the middle.
	 */
	MIDDLE,

	/**
	 * The last element.
	 */
	LAST,

	/**
	 * The only element.
	 */
	ONLY
}